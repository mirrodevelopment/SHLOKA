/**
 * Get all catalog items
 */
export function getAllSarees() {
  return SHLOKA_CATALOG;
}

/**
 * Get saree by ID
 */
export function getSareeById(id) {
  return SHLOKA_CATALOG.find((s) => s.id === id) || null;
}

/**
 * Search sarees with query and optional category filter
 */
export function searchSarees(query = '', category = 'All') {
  const q = query.trim().toLowerCase();
  return SHLOKA_CATALOG.filter((saree) => {
    const matchesCategory =
      category === 'All' ||
      saree.category.toLowerCase() === category.toLowerCase() ||
      saree.tags.some((t) => t.toLowerCase() === category.toLowerCase());

    if (!q) return matchesCategory;

    const matchesQuery =
      saree.name.toLowerCase().includes(q) ||
      saree.subtitle.toLowerCase().includes(q) ||
      saree.category.toLowerCase().includes(q) ||
      saree.fabric.toLowerCase().includes(q) ||
      saree.color.toLowerCase().includes(q) ||
      saree.craft.toLowerCase().includes(q) ||
      saree.tags.some((t) => t.toLowerCase().includes(q));

    return matchesCategory && matchesQuery;
  });
}
